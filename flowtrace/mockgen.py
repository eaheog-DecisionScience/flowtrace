import json
from pathlib import Path
from typing import Any, Dict, List, Optional


def generate_mock_test(trace_data: Dict[str, Any], target_function: Optional[str] = None,
                       mock_categories: Optional[List[str]] = None) -> str:
    """Generates a standalone pytest test script with mocks synthesized from recorded trace events."""
    if not mock_categories:
        mock_categories = ["Database", "Network", "Framework"]

    events = trace_data.get("events", [])
    calls = [e for e in events if e.get("type") == "call"]
    returns = {e.get("call_id"): e for e in events if e.get("type") == "return"}

    # Identify target function
    target_call = None
    if target_function:
        for c in calls:
            if c.get("function") == target_function or target_function in c.get("function", ""):
                target_call = c
                break
    if not target_call and calls:
        target_call = calls[0]

    if not target_call:
        return "# No calls found in trace to generate test."

    target_id = target_call.get("call_id")
    target_fn_name = target_call.get("function")
    target_mod = target_call.get("module", "")
    target_args = target_call.get("args", {})
    target_ret = returns.get(target_id, {}).get("return_value")

    # Find external downstream dependencies to mock
    # A call is downstream if its parent_id chain leads back to target_id
    id_to_parent = {e.get("call_id"): e.get("parent_id") for e in calls}
    
    def is_descendant(cid, ancestor_id):
        curr = cid
        while curr:
            curr = id_to_parent.get(curr)
            if curr == ancestor_id:
                return True
        return False

    downstream_calls = [
        c for c in calls
        if is_descendant(c.get("call_id"), target_id)
    ]

    mocks = []
    seen_funcs = set()
    for c in downstream_calls:
        cat = c.get("category")
        fn = c.get("function", "")
        mod = c.get("module", "")
        cid = c.get("call_id")
        ret = returns.get(cid, {}).get("return_value")

        if cat in mock_categories or "Database" in fn or "request" in fn or "api" in fn.lower():
            full_path = f"{mod}.{fn}" if mod else fn
            if full_path not in seen_funcs:
                seen_funcs.add(full_path)
                mocks.append({
                    "symbol": full_path,
                    "function_name": fn.split(".")[-1],
                    "args": c.get("args", {}),
                    "return_value": ret
                })

    # Build the pytest test file
    lines = [
        "# Auto-generated by Flowtrace Time-Travel Mock Generator",
        "# Replays real execution without external databases or network calls.",
        "",
        "import pytest",
        "from unittest.mock import patch, MagicMock",
        ""
    ]

    if target_mod:
        lines.append(f"from {target_mod} import {target_fn_name.split('.')[0]}")
    lines.append("")

    test_name = f"test_{target_fn_name.split('.')[-1]}_mocked"
    lines.append(f"def {test_name}():")
    lines.append("    # --- Setup Mocks ---")

    if not mocks:
        lines.append("    # No external database/network calls detected. Direct execution:")
    else:
        for m in mocks:
            var_name = f"mock_{m['function_name'].lower()}"
            lines.append(f"    # Mocking: {m['symbol']}")

    # Wrap in patch context managers
    indent = "    "
    patch_vars = []
    for i, m in enumerate(mocks):
        var_name = f"mock_{m['function_name'].lower()}_{i}"
        patch_vars.append((m, var_name))
        lines.append(f"{indent}with patch('{m['symbol']}') as {var_name}:")
        indent += "    "
        ret_val = m['return_value']
        if isinstance(ret_val, dict) and "__type__" in ret_val:
            clean_attrs = {k: v for k, v in ret_val.items() if not k.startswith("__")}
            lines.append(f"{indent}_mock_obj = MagicMock(**{repr(clean_attrs)})")
            lines.append(f"{indent}_mock_obj.to_dict.return_value = {repr(clean_attrs)}")
            lines.append(f"{indent}{var_name}.return_value = _mock_obj")
        else:
            lines.append(f"{indent}{var_name}.return_value = {repr(ret_val)}")

    lines.append("")
    lines.append(f"{indent}# --- Execute Target Function ---")
    arg_str = ", ".join(f"{k}={repr(v)}" for k, v in target_args.items() if k not in ("self", "cls"))
    lines.append(f"{indent}result = {target_fn_name}({arg_str})")
    lines.append("")
    lines.append(f"{indent}# --- Assertions ---")
    if isinstance(target_ret, dict):
        for k, v in target_ret.items():
            if not isinstance(v, (dict, list)):
                lines.append(f"{indent}assert result[{repr(k)}] == {repr(v)}")
            else:
                lines.append(f"{indent}assert {repr(k)} in result")
    elif target_ret is not None:
        lines.append(f"{indent}assert result == {repr(target_ret)}")
    else:
        lines.append(f"{indent}assert result is not None or result is None")

    for m, var_name in patch_vars:
        lines.append(f"{indent}assert {var_name}.called, '{m['symbol']} was expected to be called'")

    return "\n".join(lines) + "\n"
